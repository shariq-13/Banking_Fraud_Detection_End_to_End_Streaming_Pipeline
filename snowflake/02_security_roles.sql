-- Step 2 of 2. Creates a least-privilege role and user for the app.
-- Run as ACCOUNTADMIN AFTER 01_create_objects.sql.
--
-- BEFORE RUNNING: replace REPLACE_WITH_STRONG_PASSWORD with a real password.
-- Do not commit that password. Copy the same value into SNOWFLAKE_PASSWORD in .env.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS FRAUD_ROLE;

CREATE USER IF NOT EXISTS FRAUD_APP
    PASSWORD = 'REPLACE_WITH_STRONG_PASSWORD'
    DEFAULT_ROLE = FRAUD_ROLE
    DEFAULT_WAREHOUSE = FRAUD_WH
    DEFAULT_NAMESPACE = BANKING_FRAUD.RAW
    MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE FRAUD_ROLE TO USER FRAUD_APP;

GRANT USAGE ON WAREHOUSE FRAUD_WH TO ROLE FRAUD_ROLE;
GRANT USAGE ON DATABASE BANKING_FRAUD TO ROLE FRAUD_ROLE;
GRANT USAGE ON SCHEMA BANKING_FRAUD.RAW TO ROLE FRAUD_ROLE;
GRANT USAGE ON SCHEMA BANKING_FRAUD.ANALYTICS TO ROLE FRAUD_ROLE;

-- The loader writes to RAW tables and creates temporary stages for write_pandas.
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA BANKING_FRAUD.RAW TO ROLE FRAUD_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA BANKING_FRAUD.RAW TO ROLE FRAUD_ROLE;
GRANT CREATE STAGE ON SCHEMA BANKING_FRAUD.RAW TO ROLE FRAUD_ROLE;
GRANT CREATE FILE FORMAT ON SCHEMA BANKING_FRAUD.RAW TO ROLE FRAUD_ROLE;

-- dbt builds staging and mart models in ANALYTICS.
GRANT ALL ON SCHEMA BANKING_FRAUD.ANALYTICS TO ROLE FRAUD_ROLE;
