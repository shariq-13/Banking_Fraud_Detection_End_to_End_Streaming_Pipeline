-- Step 1 of 2. Creates the warehouse, database, schemas and tables.
-- Run as SYSADMIN, or as ACCOUNTADMIN on a trial account.
-- Run in order: this file first, then 02_security_roles.sql.

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS FRAUD_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Warehouse for the banking fraud learning project';

CREATE DATABASE IF NOT EXISTS BANKING_FRAUD;
CREATE SCHEMA IF NOT EXISTS BANKING_FRAUD.RAW;
CREATE SCHEMA IF NOT EXISTS BANKING_FRAUD.ANALYTICS;

USE WAREHOUSE FRAUD_WH;
USE DATABASE BANKING_FRAUD;
USE SCHEMA RAW;

-- Warehouse table. All timestamps are UTC.
-- Snowflake accepts PRIMARY KEY but does not enforce it. The MERGE in the
-- loader is what prevents duplicates.
CREATE TABLE IF NOT EXISTS RAW.TRANSACTIONS (
    TRANSACTION_ID        VARCHAR NOT NULL,
    CUSTOMER_ID           VARCHAR NOT NULL,
    ACCOUNT_ID            VARCHAR NOT NULL,
    AMOUNT                NUMBER(14, 2) NOT NULL,
    CURRENCY              VARCHAR NOT NULL,
    MERCHANT_CATEGORY     VARCHAR NOT NULL,
    COUNTRY               VARCHAR NOT NULL,
    TRANSACTION_TYPE      VARCHAR NOT NULL,
    TRANSACTION_TIMESTAMP TIMESTAMP_NTZ NOT NULL,
    RISK_SCORE            NUMBER(3, 0) NOT NULL,
    RISK_LEVEL            VARCHAR NOT NULL,
    IS_FRAUD_FLAG         BOOLEAN NOT NULL,
    RULE_REASONS          VARCHAR,
    LOADED_AT             TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (TRANSACTION_ID)
);

-- Landing table used by the loader before MERGE.
CREATE TABLE IF NOT EXISTS RAW.TRANSACTIONS_STAGING LIKE RAW.TRANSACTIONS;

-- Tracks which S3 Silver files were loaded, so each file loads once.
CREATE TABLE IF NOT EXISTS RAW.LOADED_FILES (
    S3_KEY     VARCHAR NOT NULL PRIMARY KEY,
    ROW_COUNT  NUMBER,
    LOADED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
